export function getBlogBySlug(slug) {
  if (!slug) return null;
  const decoded = decodeURIComponent(slug).toLowerCase();
  return (
    BLOG_POSTS.find(
      (b) => b.slug.toLowerCase() === decoded || encodeURIComponent(b.slug) === decoded
    ) || null
  );
}

